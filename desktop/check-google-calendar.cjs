const assert = require("node:assert/strict");
const fs = require("node:fs/promises");
const {tmpdir} = require("node:os");
const {join} = require("node:path");
const {pathToFileURL} = require("node:url");
const {app, BrowserWindow} = require("electron");

(async () => {
  const root = process.cwd();
  const profile = await fs.mkdtemp(join(tmpdir(),"stillwater-calendar-check-"));
  app.setPath("userData",profile);
  app.setAppPath(root);
  const vault = join(profile,"vault");
  await fs.mkdir(vault);
  await fs.writeFile(join(profile,"vault-path.txt"),vault);
  const time = new Date(Date.now()+3600000).toISOString().replace(/[-:]/g,"").replace(/\.\d+Z$/,"Z");
  const event = (id,title) => ["BEGIN:VEVENT","UID:"+id,"DTSTART:"+time,"SUMMARY:"+title,"END:VEVENT"].join("\r\n");
  const calendar = (...events) => ["BEGIN:VCALENDAR",...events,"END:VCALENDAR"].join("\r\n");
  await fs.writeFile(join(profile,"calendar.ics"),calendar(event("local","Imported fixture")));
  const address = "https://calendar.google.com/calendar/ical/fixture/private-synthetic/basic.ics";
  let source = calendar(event("remote","Calendar fixture"),event("other","Canceled later"));
  let offline = false;
  globalThis.fetch = async (url,options) => {
    assert.equal(url,address);
    assert.equal(options.redirect,"error");
    if (offline) throw Error("offline");
    return new Response(source);
  };
  await import(pathToFileURL(join(root,"desktop/main.ts")));
  const win=BrowserWindow.getAllWindows()[0];
  win.webContents.setBackgroundThrottling(false);
  const js=code=>win.webContents.executeJavaScript(code);
  await js(`(async()=>{
    document.querySelector("#speech-settings").open=true;
    const address=document.querySelector("#google-address");
    address.value=${JSON.stringify(address)};
    document.querySelector("#google-connect").click();
    for(let i=0;i<120 && document.querySelector("#google-sync").hidden;i++)await new Promise(r=>setTimeout(r,25));
    if(address.value || !document.querySelector("#agenda-events").textContent.includes("Calendar fixture"))throw Error("Google event missing on Home");
    document.querySelector("#speech-settings").open=false;
    [...document.querySelectorAll("#agenda-events button")].find(b=>b.textContent.includes("Calendar fixture")).click();
    for(let i=0;i<120 && document.querySelector("[name=title]").value!=="Calendar fixture";i++)await new Promise(r=>setTimeout(r,25));
    if(document.querySelector("#meeting-notes").dataset.calendarId!=="remote")throw Error("Note not linked to Google event");
    document.querySelector("#go-home").click();
  })()`);
  const cipher=await fs.readFile(join(profile,"google-calendar.bin"));
  assert.ok(!cipher.includes(Buffer.from("private-synthetic")));
  const {GoogleCalendarFeed}=await import(pathToFileURL(join(root,"desktop/google-calendar.ts")));
  const {safeStorage}=require("electron");
  const reopened=new GoogleCalendarFeed(profile,{open:async b=>(await safeStorage.decryptStringAsync(b)).result,seal:s=>safeStorage.encryptStringAsync(s)});
  await reopened.load();
  assert.equal(reopened.agenda({events:[],unsupported:0}).events.length,2);
  source=calendar(event("remote","Rescheduled fixture"));
  const sync=()=>js('window.stillwater.googleCalendar("sync")');
  const updated=await sync();
  assert.deepEqual(updated.events.map(e=>e.title).sort(),["Imported fixture","Rescheduled fixture"]);
  offline=true;
  await assert.rejects(sync(),/Could not reach Google/);
  assert.equal((await js("window.stillwater.readCalendar()")).events.length,2);
  await assert.rejects(js('window.stillwater.googleCalendar("connect","https://example.com/private.ics")'),/Paste the Google/);
  assert.equal((await js('window.stillwater.googleCalendar("disconnect")')).events[0].id,"local");
  await assert.rejects(fs.stat(join(profile,"google-calendar.bin")),{code:"ENOENT"});
  console.log("Google feed sync, Home, linked note creation, encrypted persistence, offline cache, replacement and disconnect passed.");
  app.exit(0);
})().catch(e=>{console.error(e);app.exit(1);});
