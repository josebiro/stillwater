const assert=require("node:assert/strict");
const fs=require("node:fs/promises");
const {join}=require("node:path");
const {tmpdir}=require("node:os");
const {pathToFileURL}=require("node:url");
const {randomUUID,createHash}=require("node:crypto");
const {app,BrowserWindow,Tray}=require("electron");

(async()=>{
  const root=process.cwd(), profile=await fs.mkdtemp(join(tmpdir(),"stillwater-daily-"));
  app.setPath("userData",profile);
  app.setAppPath(root);
  const vault=join(profile,"vault");
  await fs.mkdir(vault);
  await fs.writeFile(join(profile,"vault-path.txt"),vault);
  const load=name=>import(pathToFileURL(join(root,"desktop",name)));
  const {createMeeting,openMeeting}=await load("vault.ts");
  const {changeDaily,readDaily}=await load("daily.ts");
  const previousDate=new Date(Date.now()-86400000).toISOString(), tomorrow=new Date(Date.now()+86400000);
  const anchor=randomUUID(), segment={id:anchor,source:"system",startMs:4000,endMs:6500,text:"I will send the revised layout to Maya."};
  const previous=await createMeeting(vault,"Studio check-in","[Moment 00:05](#moment-5000)",[segment],[],["Maya"],false,{id:"studio",start:previousDate},"topic: Design");
  const other=await createMeeting(vault,"Studio check-in","Unrelated meeting.",[],[],[],false,{id:"other",start:previousDate});
  const m=await openMeeting(vault,previous), id=m.metadata.meetingId, second=(await openMeeting(vault,other)).metadata.meetingId;
  const draftId=randomUUID();
  await fs.writeFile(join(previous,"enhancement-"+draftId+".json"),JSON.stringify({schemaVersion:1,id:draftId,createdAt:previousDate,transcriptRevision:1,
    inputHash:createHash("sha256").update(JSON.stringify({notes:m.notes,transcript:m.segments})).digest("hex"),
    draft:{summary:"Layout",actions:[{text:"Send the revised layout.",segmentIds:[anchor]}]}}));
  await changeDaily(vault,{type:"attach",ids:[id,second],name:"project: Studio"});
  await changeDaily(vault,{type:"rename",original:"project: Studio",name:"project: Atlas"});
  await changeDaily(vault,{type:"detach",ids:[second],name:"project: Atlas"});
  let state=await readDaily(vault);
  assert.deepEqual(state.meetings.find(m=>m.id===id).tags.sort(),["project: Atlas","topic: Design"]);
  assert.deepEqual(state.meetings.find(m=>m.id===second).tags,[]);
  const task=state.commitments[0];
  await changeDaily(vault,{type:"commitment",id:task.id,status:"confirmed",recipient:"Maya"});
  for(const [text,reason] of [["Ship Thursday",""],["Ship Monday","Allow time for review."]]) {
    await changeDaily(vault,{type:"decision",meeting:id,project:"Atlas",subject:"Launch date",text,reason,anchor});
  }
  const stamp=tomorrow.toISOString().replace(/[-:]/g,"").replace(/\.\d+Z$/,"Z");
  await fs.writeFile(join(profile,"calendar.ics"),["BEGIN:VCALENDAR","BEGIN:VEVENT","UID:studio","DTSTART:"+stamp,
    "SUMMARY:Upcoming studio","ATTENDEE;CN=Maya:mailto:maya@example.test","END:VEVENT","END:VCALENDAR"].join("\r\n"));
  let trayMenu;
  const originalMenu=Tray.prototype.setContextMenu;
  Tray.prototype.setContextMenu=function(menu) {
    trayMenu=menu;
    return originalMenu.call(this,menu);
  };
  await load("main.ts");
  Tray.prototype.setContextMenu=originalMenu;
  const win=BrowserWindow.getAllWindows()[0];
  win.webContents.setBackgroundThrottling(false);
  const js=code=>win.webContents.executeJavaScript(code);
  const quickItem=trayMenu.items.find(item=>item.label.startsWith("Bring this up with"));
  assert.ok(quickItem,"Missing tray question action");
  quickItem.click();
  await js(`(async()=>{
    const get=id=>document.getElementById(id);
    const wait=async(test,message)=>{for(let i=0;i<240;i++){if(test())return;await new Promise(r=>setTimeout(r,25));}throw Error(message+": "+get("daily-error").textContent);};
    const clickText=(container,text)=>[...container.querySelectorAll("button")].find(b=>b.textContent===text).click();
    const box=get("daily-content");
    await wait(()=>get("owed-preview").textContent.includes("Maya"),"owed preview");
    await wait(()=>get("daily-dialog").open,"tray question composer");
    const fields=box.querySelectorAll("input"); fields[0].value="Maya";fields[1].value="Which tests should we run?";
    clickText(box,"Save question");await wait(()=>box.querySelector("p")?.textContent.includes("Which tests"),"save question");get("daily-close").click();
    get("manage-labels").click();
    box.querySelector("select").value="topic";box.querySelector("input").value="Test coverage";
    clickText(box,"Create label");await wait(()=>box.textContent.includes("topic: Test coverage"),"create shared label");
    get("daily-close").click();get("batch-labels").click();
    box.querySelector("select").value="topic";box.querySelector("input").value="Test coverage";
    for (const check of box.querySelectorAll("input[type=checkbox]"))check.click();
    if (!box.textContent.includes("2 selected"))throw Error("Batch count");
    clickText(box,"Add to selected");await wait(()=>!get("daily-dialog").open,"apply batch");
    get("manage-labels").click();
    const row=[...box.children].find(el=>el.classList.contains("daily-row")&&el.textContent.includes("Test coverage"));
    clickText(row,"Rename");box.querySelector("input").value="Quality";
    clickText(box,"Rename label");await wait(()=>box.textContent.includes("topic: Quality"),"rename shared label");
    get("daily-close").click();
    get("decision-history").click();
    if(!box.querySelector(".daily-row").textContent.includes("Ship Monday")||!box.textContent.includes("Earlier decision"))throw Error("Decision order");
    get("daily-close").click();get("feature-open").click();
    await wait(()=>get("meeting-prep").textContent.includes("Which tests"),"prep");
    if(!get("meeting-prep").textContent.includes("Ship Monday")||!get("meeting-prep").textContent.includes("Send the revised layout"))throw Error("Previous meeting context");
    clickText(get("meeting-prep"),"Add to agenda");
    if(!document.querySelector("[name=notes]").value.includes("Ship Monday"))throw Error("Carry decision");
    clickText(get("meeting-prep"),"Mark discussed");await wait(()=>!get("meeting-prep").textContent.includes("Which tests"),"discuss");
    await openSavedMeeting(${JSON.stringify(state.meetings.find(m=>m.id===id).path)},undefined,"journal");
    await wait(()=>get("saved-labels").textContent.includes("Atlas"),"saved labels");
    await wait(()=>get("saved-labels").textContent.includes("topic: Quality"),"existing renamed chip");
    clickText(get("saved-labels"),"topic: Quality");
    await wait(()=>!get("folder-view").hidden&&get("folder-notes").querySelectorAll(".note-row").length===2,"label page lists both tagged notes");
    await openSavedMeeting(${JSON.stringify(state.meetings.find(m=>m.id===id).path)},undefined,"journal");
    await wait(()=>get("saved-labels").textContent.includes("topic: Quality"),"reopened note");
    get("saved-labels").querySelector('[aria-label="Remove topic: Quality"]').click();
    await wait(()=>!get("saved-labels").textContent.includes("Quality"),"remove one label");
    get("saved-labels").querySelector(".add-label").click();
    await wait(()=>!get("folder-picker").hidden,"label picker");
    const search=get("folder-picker-search");search.value="person: Maya";search.dispatchEvent(new Event("input"));
    search.dispatchEvent(new KeyboardEvent("keydown",{key:"Enter"}));
    await wait(()=>get("saved-labels").textContent.includes("person: Maya"),"add inline label");
    search.dispatchEvent(new KeyboardEvent("keydown",{key:"Escape",bubbles:true}));
    get("record-decision").click();
    const decisionFields=box.querySelectorAll("input");decisionFields[0].value="Launch date";decisionFields[1].value="Ship Tuesday";decisionFields[2].value="Complete QA";
    box.querySelectorAll("select")[1].selectedIndex=1;
    clickText(box,"Save decision");await wait(()=>box.textContent.includes("Ship Tuesday"),"save sourced decision");
    box.querySelector(".daily-row button").click();await wait(()=>box.querySelector("blockquote")?.textContent.includes("revised layout"),"decision source");
    get("daily-close").click();
    get("meeting-note-citations").querySelector("a").click();
    await wait(()=>get("saved-transcript-panel").open,"marker opens transcript");
    get("go-home").click();get("commitments").click();clickText(box,"Mark done");await wait(()=>!get("owed-preview").textContent,"complete");
  })()`);
  state=await readDaily(vault);
  assert.ok(state.questions[0].discussed);
  assert.equal(state.commitments[0].status,"done");
  await win.loadFile(join(root,"desktop/index.html"));
  assert.equal(await js('document.getElementById("owed-preview").textContent'),"");
  console.log("Daily journal passed label batches, series prep, attendee reminders, commitments, decisions and transcript moments.");
  await js("initialLibraryLoad");
  await js("window.stillwater.dailyJournal().then(()=>true)");
  await fs.rm(vault,{recursive:true,force:true});app.exit(0);
})().catch(error=>{console.error(error);app.exit(1)});
